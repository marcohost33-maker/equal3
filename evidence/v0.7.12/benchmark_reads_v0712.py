"""Benchmarks v0.7.11 vs v0.7.12 raw read semantics, isolated subprocesses.

No independent patch provenance, hardware isolation, or production SLA.
Writes for common DB fixtures are always generated by the original version.
"""
import argparse
import csv
import json
import os
import pathlib
import statistics
import subprocess
import sys
import tempfile

KEY=b'R'*32
WORKER=r'''
import json,statistics,sys,time
from pathlib import Path
import state_store
assert Path(state_store.__file__).resolve()==Path(sys.argv[2]).resolve(), 'wrong source bound'
s=state_store.StateStore(Path(sys.argv[1]),key=b'R'*32)
call=s.read
for _ in range(5):call()
ns=[]
for _ in range(40):
 t=time.perf_counter_ns();call();ns.append((time.perf_counter_ns()-t)/1e6)
ns.sort()
print(json.dumps({'median_ms':statistics.median(ns),'p95_ms':ns[37],'n':len(ns)}))
'''


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('original')
    ap.add_argument('candidate')
    ap.add_argument('csv_output')
    ap.add_argument('summary_output')
    args=ap.parse_args()
    original=pathlib.Path(args.original).resolve()
    candidate=pathlib.Path(args.candidate).resolve()
    with tempfile.TemporaryDirectory(prefix='eq3-read-benchmark-') as t:
        sys.path.insert(0,str(original))
        import state_store
        records=[]
        for commits in (0,50,250):
            file=pathlib.Path(t)/('s'+str(commits)+'.sqlite')
            st=state_store.StateStore.create(file,key=KEY,initial=b'A'*1024)
            for i in range(commits):
                proposal,_=state_store.prepare_update(st,(f'v{i}:'.encode()+b'B'*1016)[:1024])
                st.apply(proposal)
            # ABBA ordering of version comparisons (not independent hardware isolation)
            for run_idx, name in enumerate(('old','new','new','old')):
                folder=original if name=='old' else candidate
                env=os.environ.copy()
                env['PYTHONPATH']=str(folder)
                proc=subprocess.run([sys.executable,'-c',WORKER,str(file),str(folder/'state_store.py')],env=env,cwd=str(folder),
                                    capture_output=True,text=True,check=True,timeout=30)
                item=json.loads(proc.stdout)
                records.append({'commits':commits,'condition':name,'round':run_idx+1,
                                **item})
        with open(args.csv_output,'w',newline='') as out:
            w=csv.DictWriter(out,fieldnames=['commits','condition','round','median_ms','p95_ms','n'])
            w.writeheader();w.writerows(records)
        summary={}
        for commits in (0,50,250):
            summary[str(commits)]={}
            for name in ('old','new'):
                r=[x['median_ms'] for x in records if x['commits']==commits and x['condition']==name]
                summary[str(commits)][name]={'median_of_round_medians_ms':statistics.median(r),'round_medians_ms':r}
        pathlib.Path(args.summary_output).write_text(json.dumps(summary,indent=2,sort_keys=True))
        print(json.dumps(summary,indent=2))

if __name__ == '__main__':main()
